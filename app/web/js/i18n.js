/** All dictionaries by language code. */
export const DICTS = Object.freeze({ zh, en });

/** Every known i18n key (from the default language). */
export const I18N_KEYS = Object.freeze(Object.keys(zh));

let currentLang = DEFAULT_LANG;

/** True when `lang` has a dictionary. */
export function hasLang(lang) {
  return Object.prototype.hasOwnProperty.call(DICTS, lang);
}

/** Normalize to a supported language, falling back to the default. */
export function normalizeLang(lang) {
  return hasLang(lang) ? lang : DEFAULT_LANG;
}

/** Set the active language (ignored when unsupported). */
export function setLang(lang) {
  currentLang = normalizeLang(lang);
  return currentLang;
}

/** Current language code. */
export function getLang() {
  return currentLang;
}

/** Languages with a dictionary (derived from config for a single source of truth). */
export function availableLangs() {
  return AVAILABLE_LANGS.filter((lang) => LANGUAGES.includes(lang));
}

/** Replace `{name}` placeholders from `vars`. */
export function interpolate(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

/** Look up a raw template (no interpolation), with zh fallback. */
export function raw(key, lang = currentLang) {
  const dict = DICTS[normalizeLang(lang)];
  if (Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];
  if (Object.prototype.hasOwnProperty.call(zh, key)) return zh[key];
  return undefined;
}

/** True when `key` exists in `lang` (or the default dictionary). */
export function hasKey(key, lang = currentLang) {
  return raw(key, lang) !== undefined;
}

/**
 * Translate `key`, interpolating `{name}` placeholders.
 * Missing keys are returned verbatim so they are visible (and testable).
 */
export function t(key, vars) {
  const template = raw(key);
  if (template === undefined) return String(key);
  return vars ? interpolate(template, vars) : template;
}

/** Translate a key and record it as missing (used by the test suite). */
export function missingKeys(lang = currentLang) {
  const dict = DICTS[normalizeLang(lang)];
  return I18N_KEYS.filter((key) => !Object.prototype.hasOwnProperty.call(dict, key));
}

/**
 * Format a Unix timestamp (seconds) as localized relative time.
 * @param {number} seconds Unix seconds
 * @param {number} [nowSeconds] injectable clock (default: real now)
 */
export function formatRelativeTime(seconds, nowSeconds = Math.floor(Date.now() / 1000)) {
  const value = Number(seconds);
  if (!Number.isFinite(value) || value <= 0) return t('common.unknown');
  const delta = Math.max(0, nowSeconds - value);
  if (delta < 60) return t('time.justNow');
  if (delta < 3600) return t('time.minutesAgo', { n: Math.floor(delta / 60) });
  if (delta < 86400) return t('time.hoursAgo', { n: Math.floor(delta / 3600) });
  return t('time.daysAgo', { n: Math.floor(delta / 86400) });
}

/** Error copy (title + "what to do next") for a protocol error code. */
export function errorCopy(code) {
  const base = hasKey(`error.${code}.title`) ? `error.${code}` : 'error.unknown';
  return { title: t(`${base}.title`), next: t(`${base}.next`) };
}

/** Close-reason copy for a WebSocket close code. */
export function closeCopy(code) {
  const base = hasKey(`close.${code}.title`) ? `close.${code}` : 'close.unknown';
  return { title: t(`${base}.title`), next: t(`${base}.next`) };
}
